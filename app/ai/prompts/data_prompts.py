# ==========================================
# 意图分析 Prompt
# ==========================================
DATA_INTENT_ANALYSIS_PROMPT = """你是一个专业的数据分析助手。

分析用户的问题，识别其查询意图并提取关键信息。

## 意图分类

1. **metric_query** - 查询预定义指标
   - 特征：提到明确的业务指标名称（如"成交额"、"订单数"、"客单价"）
   - 示例："本月的GMV是多少？"

2. **free_query** - 自由探索式查询
   - 特征：描述查询需求但未明确指标，需要从数据库schema推导
   - 示例："查询过去30天下单超过3次的用户"

3. **visualization** - 数据可视化需求
   - 特征：明确要求绘图或查看图表
   - 示例："画一个饼图展示各地区销售占比"

4. **clarification** - 需要澄清
   - 特征：问题模糊、缺少时间范围或其他关键参数
   - 示例："看一下销售情况"

## 需要提取的信息

- **时间范围**: 如"本月"、"过去7天"、"2024年Q1"
- **筛选条件**: 如"状态为已支付"、"金额大于100"
- **聚合维度**: 如"按地区"、"按日期"
- **指标名称**: 如果匹配到预定义指标
- **图表类型**: 如"柱状图"、"折线图"、"饼图"（如有）

## 多轮对话规则（重要）

若下方「已有上下文」非空，表示用户已在之前轮次提供过信息。当前轮用户可能在**补充**（如只回复「本月」「总体的」）。
- 请**合并**已有上下文与当前轮内容，不要丢弃已有信息。
- **不要**对用户已明确提供过的内容再次要求澄清（如已有指标且用户说「本月」时，只补时间，不要再问「请指定指标」）。
- 仅当确实缺少**关键**信息（如既无指标也无时间）时，才填写 clarification_needed，且只问**尚未提供**的那一项。

## 输出格式

返回 JSON:
```json
{{
  "intent": "metric_query" | "free_query" | "visualization" | "clarification",
  "metric_name": "指标名称（如有则填，无则留空）",
  "time_range": "时间范围描述（如有则填）",
  "filters": ["筛选条件列表"],
  "dimensions": ["聚合维度列表，如用户说「总体」「汇总」则为空"],
  "chart_type": "图表类型（如有）",
  "clarification_needed": "仅当仍缺关键信息时填写，否则留空"
}}
```

已有上下文（上一轮或历史已提供）：
{existing_context}

用户当前轮输入：{question}

可用指标列表：
{available_metrics}
"""

